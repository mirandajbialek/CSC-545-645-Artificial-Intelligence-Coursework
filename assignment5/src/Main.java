	public static void computeTimes(int numIterations) throws Exception{

		Map map = new Map();
		initCompleteUSMap(map);
		//initMap(map);

		//eval time of functions
		CSP<Integer> csp = map.createCSP();

		long startTime, endTime;
		long timeBTTotal = 0;
		long timeFBTTotal = 0;
		long timeAC3BTTotal = 0;
		long timeMinConflictsTotal = 0;

		double timeBTAvg = 0;
		double timeFBTAvg  = 0;
		double timeAC3BTAvg  = 0;
		double timeMinConflictsAvg  = 0;

		for (int i = 0; i < numIterations; i++){
			
			//Backtracking plain
			csp = map.createCSP();
			CSPSolver solver = new BacktrackingCSPSolver();
			startTime = System.nanoTime();
			solver.solve(csp);
			endTime = System.nanoTime();
			timeBTTotal += endTime - startTime;

			//Backtracking with forward checking
			csp = map.createCSP();
			solver = new ForwardCheckingCSPSolver();
			startTime = System.nanoTime();
			solver.solve(csp);
			endTime = System.nanoTime();
			timeFBTTotal += endTime - startTime;

			//Backtracking with AC-3
			csp = map.createCSP();
			solver = new BacktrackingCSPSolver();
			AC3.ac3(csp);
			startTime = System.nanoTime();
			solver.solve(csp);
			endTime = System.nanoTime();
			timeAC3BTTotal += endTime - startTime;

			//Backtracking with min conflicts
			csp = map.createCSP();
			solver = new MinConflicts();
			startTime = System.nanoTime();
			solver.solve(csp);
			endTime = System.nanoTime();
			timeMinConflictsTotal += endTime - startTime;
		}

		// System.out.println("TOTAL TIMES (n)");
		// System.out.println("Backtracking : " + timeBTTotal);
		// System.out.println("Backtracking w/ FC: " + timeFBTTotal);
		// System.out.println("Backtracking w/ AC3: " + timeAC3BTTotal);
		// System.out.println("Min Conflicts : " + timeMinConflictsTotal);

		timeBTAvg = timeBTTotal/numIterations/1e6;
		timeFBTAvg  = timeFBTTotal/numIterations/1e6;
		timeAC3BTAvg  = timeAC3BTTotal/numIterations/1e6;
		timeMinConflictsAvg  = timeMinConflictsTotal/numIterations/1e6;

		System.out.println("AVERAGE TIMES (ms) (without initial assignment)");
		System.out.println("Backtracking : " + timeBTAvg);
		System.out.println("Backtracking w/ FC: " + timeFBTAvg);
		System.out.println("Backtracking w/ AC3: " + timeAC3BTAvg);
		System.out.println("Min Conflicts : " + timeMinConflictsAvg);
	}

